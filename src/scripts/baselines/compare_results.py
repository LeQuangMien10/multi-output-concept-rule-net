"""
compare_results.py — Aggregate ICRL vs. CRL-RRL vs. classic-ML metrics.json
files across datasets into one comparison table (accuracy + rule quality).

Not dataset-agnostic by design: the set of runs to compare is a handful of
known paths, explicit and readable beats a generic file-discovery scan here.

Usage: python -m src.scripts.baselines.compare_results
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]


def _load(path: Path) -> dict | None:
    if path is None or not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def _rule_count_from_icrl(metrics: dict) -> int | None:
    return metrics.get("num_rules") if metrics else None


DATASETS = {
    "MNIST_Math (original, digit3 pred)": {
        "icrl": ROOT / "outputs/icrl_coherence_fixed/metrics.json",
        "crl_rrl": ROOT / "outputs/baselines/mnist_math_v3/crl_rrl/metrics.json",
        "decision_tree": ROOT / "outputs/baselines/mnist_math_v3/decision_tree_metrics.json",
        "logistic_regression": ROOT / "outputs/baselines/mnist_math_v3/logistic_regression_metrics.json",
    },
    "Fitzpatrick17k": {
        "icrl": ROOT / "outputs/fitzpatrick_icrl/metrics.json",
        "crl_rrl": ROOT / "outputs/baselines/fitzpatrick/crl_rrl/metrics.json",
        "decision_tree": ROOT / "outputs/baselines/fitzpatrick/decision_tree_metrics.json",
        "logistic_regression": ROOT / "outputs/baselines/fitzpatrick/logistic_regression_metrics.json",
    },
}


def main():
    lines = []
    lines.append("| Dataset | System | Test accuracy | Val accuracy | # Rules | Notes |")
    lines.append("|---|---|---|---|---|---|")

    for ds_name, paths in DATASETS.items():
        icrl = _load(paths["icrl"])
        crl = _load(paths["crl_rrl"])
        tree = _load(paths["decision_tree"])
        lr = _load(paths["logistic_regression"])

        rows = [
            ("ICRL (ours)", icrl, icrl.get("num_rules") if icrl else None,
             f"conf mean={icrl['rule_confidence_stats']['mean']:.3f}" if icrl and "rule_confidence_stats" in icrl else ""),
            ("CRL/RRL logic layers", crl, crl.get("num_rules") if crl else None, ""),
            ("Decision Tree (CART)", tree, tree.get("num_rules") if tree else None,
             f"depth={tree.get('tree_depth')}" if tree else ""),
            ("Logistic Regression (no rules)", lr, None, "no-structure control"),
        ]

        first = True
        for name, m, n_rules, note in rows:
            ds_col = ds_name if first else ""
            first = False
            if m is None:
                lines.append(f"| {ds_col} | {name} | — | — | — | not run yet |")
                continue
            test_acc = m.get("test_accuracy")
            val_acc = m.get("val_accuracy")
            test_str = f"{test_acc:.4f}" if test_acc is not None else "—"
            val_str = f"{val_acc:.4f}" if val_acc is not None else "—"
            rules_str = str(n_rules) if n_rules is not None else "—"
            lines.append(f"| {ds_col} | {name} | {test_str} | {val_str} | {rules_str} | {note} |")

    table = "\n".join(lines)
    print(table)

    out_path = ROOT / "reports" / "baseline_comparison.md"
    out_path.parent.mkdir(exist_ok=True)
    out_path.write_text(
        "# Baseline comparison — ICRL vs. CRL/RRL vs. classic ML\n\n"
        "Auto-generated by src/scripts/baselines/compare_results.py\n\n" + table + "\n",
        encoding="utf-8",
    )
    print(f"\n[INFO] Written to {out_path}")


if __name__ == "__main__":
    main()
